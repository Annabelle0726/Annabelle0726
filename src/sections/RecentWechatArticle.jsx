function TasteArticle({ images }) {
  return <>
    <Figure images={images} index={0} kind="cover" alt="让最初的喜欢，留在最后的页面里，文章封面" />
    <p>最近修改 Taste Studio 的网页时，我反复遇到一种落差：草图里明明有让我心动的地方，等它变成真正的页面，那种感觉却淡了。花还在，颜色也没有错，但花瓣被裁掉了一部分，文字挤进了原本舒服的留白，点一下按钮，整个画面又像一块沉重的布景，齐齐挪向另一边。每一处似乎都能解释，放在一起，却已经离最初的喜欢有些远了。</p>
    <p>这些不满意，也成了这次更新的起点。Taste Studio 是我为 AI 设计协作整理的一套 Skill，你可以把它理解成一份工作方法：让 AI 先理解页面要为谁服务，再探索几种不同的设计，听取你的选择，逐步把它做出来。这次，我继续补上了从草图到网页、从视觉到操作之间的细节，<strong>希望那些让人愿意多看一眼的东西，在真正使用时也能留下来</strong>。</p>
    <Figure images={images} index={1} alt="从设计草图走到可用网页配图" />
    <Chapter number="01" topic="Room for Taste">喜欢，可以从说不清楚开始</Chapter>
    <p>面对设计稿，我们未必能立刻解释自己的判断。有时只是觉得，这张更亲近，那张有些拘谨；这一处想再看一眼，另一处虽然整齐，却没有留下什么印象。这样的感受很难直接翻译成字体、间距或配色，但它已经提供了方向。我希望 Taste Studio 能给这些尚未成形的判断一点时间，让人先看到不同的可能，再慢慢辨认自己在意什么。因此，它保留了几张草图并排比较的过程：同样的内容，可以有不同的重心、阅读顺序和画面关系。AI 先听你说喜欢哪里、想改哪里，再提出建议。你不需要先学会一套设计术语，也可以只说：“我想留住花瓣边缘的水珠。”接下来的工作，就是围绕这句话，把那个细节放到值得被看见的位置。</p>
    <Figure images={images} index={2} align="aside" alt="从一点喜欢开始的设计配图" caption="从一点喜欢开始" />
    <p>那对偏好的记录也需要分寸。喜欢这朵花的近景，并不意味着以后所有页面都要放一张巨大的花。Taste Studio 会把原话、对应的画面和当时的用途一起记下，同时把设计者自己的理解单独写清。以后遇到新的项目，再回来确认这份喜欢是否仍然适用。</p>
    <p><strong>人的选择可以延续，也可以改变，记录应该为这种变化留出余地</strong></p>
    <Chapter number="02" topic="Carry It Through">把草图里动人的地方带出来</Chapter>
    <p>一张草图的吸引力，往往来自几种关系恰好成立：花枝从画面边缘探进来的位置，标题旁边留出的空白，光落在材质上的方向，还有一条很轻、却让整个画面有了精神的金线。如果实现时只留下“红色花朵、米色背景、衬线字体”这些表面特征，很容易做出一个元素相似、<strong>气质</strong>却不同的页面。</p>
    <p>这次更新把“怎样从草图走到网页”写得更具体了。开始制作前，AI 需要先辨认画面的重点，以及你明确想保留的细节，再决定哪些由排版完成，哪些需要独立的图片或装饰素材。文字要成为可以阅读、选择的真实文字，按钮要能带人去到正确的位置，图片也要为不同屏幕安排合适的呈现方式。</p>
    <Figure images={images} index={3} kind="demo" alt="草图和成品的设计细节" caption="图到成品的心动细节" />
    <p>这件事到了手机上尤其明显。电脑上舒展的布局，缩小后可能让标题拥挤，让花朵只剩一个局部，让原本重要的操作落到很远的地方。所以，手机页面需要重新安排阅读顺序和图文关系。我要检查的是：换了一块屏幕之后，<strong>最初吸引我的那个细节是否仍然看得见，第一次来到这里的人是否依然知道下一步可以做什么?</strong></p>
    <Chapter number="03" topic="A Gentle Response">让每一次点击，都有自然的回应</Chapter>
    <p>最近我说得最多的一个词，大概是“生硬”。有些页面静止时看起来不错，一操作就暴露出问题：只是切换一张图片，标题和整片背景却跟着移动；刚想点下一项，就被迫等上一段动画播完；返回之后，又得重新寻找刚才读到的位置。这些小小的停顿，会不断打断人与内容之间刚建立起来的联系。</p>
    <p>这次，我把交互体验放到了更早的设计阶段。画页面之前，就先想清楚一个人会从哪里进入，做出什么选择，得到什么回应，以及怎样继续或返回。到了具体的切换，再区分哪些元素应当稳定，哪些内容确实发生了变化。例如，换一个案例时，导航和操作位置可以留在原处，让图片与说明完成必要的更新，视线便有地方可以依靠。</p>
    <Figure images={images} index={4} kind="demo" alt="Taste Studio 交互体验演示动图" caption="交互体验" />
    <p>我想要的<strong>流畅</strong>，包含一种很细微的<strong>体贴</strong>: 按钮及时回应，内容变化有迹可循；连续点了几次，页面仍然跟得上最后的选择；想停下来自己滚动时，它也愿意把控制权交回来。对于希望减少动态效果的人，同样的信息和操作也应当完整保留。这些体验需要在真实页面里反复操作才能判断，几张漂亮的截图，还不足以说明它们已经做好。</p>
    <Chapter number="04" topic="A Fresh Pair of Eyes">让另一双眼睛，走进页面</Chapter>
    <p>做一个页面久了，很容易熟悉它的一切。我们知道入口藏在哪里，知道某张图片为什么这样裁，也知道一个不够明确的按钮原本想表达什么。可是，第一次打开网页的人没有这些背景。他只能依靠眼前的文字、位置和反馈，判断这里有什么，以及自己可以做什么。</p>
    <Figure images={images} index={5} align="aside" alt="从访客角度评审页面配图" />
    <p>因此，<strong>这次更新加入了独立的 AI 评审环节</strong>。在工具支持的情况下，由另一位没有参与当前设计或制作的 AI 助手来检查结果。对于已经可以运行的页面，它需要先像访客一样寻找入口、完成操作，再对照原来的草图和你的反馈，查看重要的细节有没有在实现中丢失。发现问题时，也要说清楚发生在哪里、怎样出现、影响了什么，方便回到同一个地方验证修改。</p>
    <p>多一次评审，并不能保证页面从此没有问题，但它能让“做好了”这句话更有依据。按钮能否顺利操作，手机上的文字是否完整，修改后有没有保住你喜欢的部分，都应该被实际检查；而关于风格的建议，也需要留出讨论的空间，不能因为另一位评审更喜欢某种排版，就覆盖你的选择。做完这一轮更新，我仍然会在自己的页面里发现不满意的地方，也仍然需要停下来，重新看一张图、一段文字和它们之间的距离。</p>
    <p><strong>Taste Studio 想认真对待的，正是这些看似微小的判断。AI 可以把许多可能带到眼前，而我们愿意留下哪一种、为什么想再靠近一点，值得在整个制作过程中被持续记得。</strong></p>
    <p>如果这篇文章对你有帮助，欢迎点个赞、点亮再看<br />关注 <strong>独钓江雪9447</strong>，我们下次见</p>
    <Figure images={images} index={6} kind="signature" alt="文章结尾动图" />
  </>;
}

export default function RecentWechatArticle({ id, language, onNavigate }) {
  const collection = collectionForArticle(id);
  const title = collection.articles.find(([route]) => route === id)[1];
  const Content = id === 'seat-for-the-dice' ? DiceArticle : TasteArticle;
  return <article className="agency-article" lang="zh-CN"><div className="article-page">
    <SectionHeader eyebrow={collection.en.toUpperCase() + ' / NOTES'} title={title} as="h1" />
    <div className="article-body">
      <Content images={articleMedia[id]} />
      <ArticleFooter routeId={id} language={language} onNavigate={onNavigate} />
    </div>
  </div></article>;
}
